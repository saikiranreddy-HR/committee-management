-- Phase 2A -- PostgreSQL Database Foundation
-- Migration 0001: users, user_roles
--
-- Source: architecturefinal-v4.5.1.md §6, entities 1-2.
--
-- Dialect mapping applied throughout this migration set, per §6's
-- "Schema Authority & Dialect Note": TEXT identifiers -> UUID,
-- INTEGER flags -> BOOLEAN, INTEGER epoch timestamps -> TIMESTAMPTZ.
-- No table, column, relationship, or CHECK constraint's business
-- meaning is changed by this dialect mapping.

-- 1. Users (committee member accounts / profile, keyed to Supabase
-- Auth identity). Per §6's Account Provisioning Rule point 5, this
-- table intentionally holds NO password/credential columns -- Supabase
-- Auth is the sole credential authority. `id` IS the Supabase Auth
-- user id (auth.users.id) -- it is never independently generated by
-- this table. The application/provisioning workflow (a later phase)
-- is responsible for supplying the Supabase Auth user id explicitly
-- at insert time (e.g. `auth.uid()` for the currently authenticated
-- user, or the newly created user's id during ADMIN-driven
-- provisioning). There is no `default gen_random_uuid()` on this
-- column precisely so that a second, independent identity can never
-- be created here by accident.
--
-- The architecture's raw schema does not specify an explicit foreign
-- key to auth.users, so none is added here -- see the Phase 2A final
-- report for this as a flagged, deliberately-not-invented ambiguity.
create table users (
    id            uuid primary key not null,
    username      text unique not null,
    display_name  text not null,
    phone_number  text,
    is_active     boolean not null default true,
    created_at    timestamptz not null
);

comment on table users is
    'Committee member accounts/profile. Credentials are managed exclusively by Supabase Auth -- this table holds identity/profile/role attribution only (architecturefinal-v4.5.1.md §6, Account Provisioning Rule).';
comment on column users.id is
    'Equal to the Supabase Auth user id (auth.users.id). Must be supplied explicitly at insert time -- this column has no default and never generates an independent identity.';

-- 2. User Roles (multi-role associative mapping). Exactly the four
-- fixed roles are valid: MEMBER, ACCOUNTANT, ADMIN, AUDITOR. Per §6.2,
-- the permitted value set is intentionally NOT enforced via a
-- database CHECK -- the client and server-side Financial RPC layer
-- are the authoritative validators of enumerated values; this is a
-- deliberate architectural decision, not an oversight.
create table user_roles (
    user_id uuid not null references users(id) on delete restrict,
    role    text not null, -- MEMBER, ACCOUNTANT, ADMIN, AUDITOR
    primary key (user_id, role)
);

create index idx_user_roles_user on user_roles(user_id);

comment on table user_roles is
    'Multi-role associative mapping. A user may hold multiple of the four fixed roles simultaneously (architecturefinal-v4.5.1.md §12.1, §12.3).';
