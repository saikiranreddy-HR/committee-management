-- Migration 0009: audit_events
--
-- Source: architecturefinal-v4.5.1.md §6, entity 14 ("Audit Events --
-- Immutable Committee Audit Trail - STRICTLY APPEND ONLY").
--
-- DECISION -- server_global_sequence generation mechanism: the
-- architecture names this column but does not explicitly prescribe
-- its PostgreSQL generation mechanism. To avoid silently inventing
-- semantics, the following explicit decision is recorded here:
--
--   server_global_sequence is a PostgreSQL-generated server-side
--   monotonically increasing sequence value used for audit ordering.
--   Clients do not supply or modify this value.
--
-- This is implemented as `bigint generated always as identity`:
--   - generated by PostgreSQL itself (backed by an implicit sequence);
--   - NOT NULL (identity columns cannot hold a null value);
--   - never client-supplied -- `GENERATED ALWAYS` rejects any INSERT
--     that attempts to specify a value, unless the caller explicitly
--     uses `OVERRIDING SYSTEM VALUE`, which no application code path
--     in this repository uses;
--   - immutable after insert -- migration 0013's
--     `trg_forbid_update_audit_events` trigger blocks ALL updates to
--     `audit_events` rows; PostgreSQL's own identity-column semantics
--     independently reject any attempt to UPDATE this specific
--     column to a non-DEFAULT value before that trigger even runs,
--     so this column is protected twice over;
--   - never reused -- a PostgreSQL identity sequence does not reissue
--     a value once advanced, including after a rolled-back insert.
--
-- No distributed ordering, timestamp-based ordering, UUID ordering,
-- or client-generated ordering is implemented for this column.
--
-- before_state_json / after_state_json are implemented as `jsonb`
-- (the idiomatic PostgreSQL type for structured JSON), consistent
-- with §6's dialect note that only the underlying type changes, never
-- the column's meaning.
--
-- The strict append-only enforcement (no UPDATE, no DELETE) is added
-- as a trigger in migration 0013 (immutability_triggers.sql), once
-- the shared trigger function exists.

create table audit_events (
    id                      uuid primary key not null default gen_random_uuid(),
    entity_type             text not null,
    entity_id               uuid not null,
    action_type             text not null,
    actor_user_id           uuid not null references users(id) on delete restrict,
    entity_version          integer not null,
    reason                  text,
    before_state_json       jsonb,
    after_state_json        jsonb not null,
    client_timestamp        timestamptz not null,
    server_timestamp        timestamptz,
    server_global_sequence  bigint generated always as identity not null
);

create index idx_audit_entity on audit_events(entity_type, entity_id, client_timestamp);

comment on table audit_events is
    'Immutable, append-only committee audit trail (§6). UPDATE/DELETE are blocked by trigger (see migration 0013), not merely by convention.';
comment on column audit_events.server_global_sequence is
    'server_global_sequence is a PostgreSQL-generated server-side monotonically increasing sequence value used for audit ordering. Clients do not supply or modify this value.';
